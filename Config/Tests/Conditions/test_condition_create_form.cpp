namespace
{
    ConditionTreeNode node(ConditionTreeNode::Kind kind, int depth, const char *uid)
    {
        ConditionTreeNode n;
        n.kind = kind;
        n.depth = depth;
        n.uid = uid;
        n.name = uid;
        return n;
    }

    // An independent model of the Windows walk (conditions_sidebar.py:1508-1513): the node itself, then its parent chain, the first folder wins.
    std::string reference_folder_context(const std::vector<ConditionTreeNode> &nodes, std::size_t index)
    {
        std::vector<const ConditionTreeNode *> ancestors; // ancestors[d] = the last node seen at depth d
        for (std::size_t i = 0; i <= index && i < nodes.size(); ++i)
        {
            const std::size_t depth = static_cast<std::size_t>(nodes[i].depth);
            ancestors.resize(depth);
            ancestors.push_back(&nodes[i]);
        }
        for (std::size_t d = ancestors.size(); d-- > 0;)
            if (ancestors[d]->kind == ConditionTreeNode::Kind::Folder)
                return ancestors[d]->uid;
        return "";
    }
}

