    BidLayer layer(const char *uid, const char *bid_uid, const char *name, int sequence, bool is_template = false, bool is_locked = false)
    {
        BidLayer l;
        l.uid = uid;
        l.bid_uid = bid_uid;
        l.name = name;
        l.sequence = sequence;
        l.is_template = is_template;
        l.is_locked = is_locked;
        return l;
    }

    // The bid's own layers by uid (what ProjectData::layers holds): every listed layer that belongs to the bid.
    std::unordered_map<std::string, Layer> own_layers(const std::vector<BidLayer> &list, const std::string &bid_uid)
    {
        std::unordered_map<std::string, Layer> own;
        for (const BidLayer &l : list)
            if (l.bid_uid == bid_uid)
            {
                Layer entry;
                entry.uid = l.uid;
                entry.name = l.name;
                own[l.uid] = entry;
            }
        return own;
    }

    ConditionChanges type_only(int type)
    {
        ConditionChanges changes;
        changes.values.condition_type = static_cast<ConditionType>(type);
        changes.mark(ConditionField::ConditionType);
        return changes;
    }

