// The rule on a tree that build_condition_tree makes (nested folders, groups, an empty folder, conditions at the top): every node's context
// equals the independent model.
TEST(CondCreateFolderContext, EveryNodeOfARealTreeAgreesWithTheModel)
{
    std::unordered_map<std::string, ConditionFolder> folders;
    folders["10"] = ConditionFolder{"10", "Walls", ""};
    folders["11"] = ConditionFolder{"11", "Interior", "10"};
    folders["12"] = ConditionFolder{"12", "Deep", "11"};
    folders["13"] = ConditionFolder{"13", "Empty", ""};
    std::unordered_map<std::string, CdnType> types;
    types["5"] = CdnType{"5", "Concrete"};
    std::unordered_map<std::string, Condition> conditions;
    auto add = [&](const char *uid, int ref, const char *folder, const char *type)
    {
        Condition c;
        c.uid = uid;
        c.name = std::string("Cond ") + uid;
        c.ref_no = ref;
        c.condition_folder_uid = folder;
        c.cdn_type_uid = type;
        conditions[uid] = c;
    };
    add("1", 1, "", "");
    add("2", 2, "10", "5");
    add("3", 3, "11", "");
    add("4", 4, "12", "5");
    add("5", 5, "12", "");
    add("6", 6, "", "5");
    const std::vector<ConditionTreeNode> nodes = build_condition_tree(conditions, folders, types);
    REQUIRE(nodes.size() > 10);
    std::size_t at_top = 0, in_a_folder = 0;
    for (std::size_t i = 0; i < nodes.size(); ++i)
    {
        SCOPED_CONTEXT("node " + std::to_string(i) + " depth " + std::to_string(nodes[i].depth) + " " + nodes[i].uid);
        const std::string expected = reference_folder_context(nodes, i);
        CHECK_STR_EQ(folder_context_uid(nodes, i), expected);
        (expected.empty() ? at_top : in_a_folder)++;
    }
    CHECK(at_top > 0);
    CHECK(in_a_folder > 0);
    // the deepest folder's conditions land in it
    for (std::size_t i = 0; i < nodes.size(); ++i)
        if (nodes[i].kind == ConditionTreeNode::Kind::Condition && (nodes[i].uid == "4" || nodes[i].uid == "5"))
            CHECK_STR_EQ(folder_context_uid(nodes, i), "12");
}

// CF-10 (a tree of 8000 nested folders is legal data): the rule is iterative, no recursion over the depth.
TEST(CondCreateFolderContext, AVeryDeepChainNeedsNoRecursion)
{
    const int depth = 8000;
    std::vector<ConditionTreeNode> nodes;
    for (int d = 0; d < depth; ++d)
        nodes.push_back(node(ConditionTreeNode::Kind::Folder, d, std::to_string(d + 1).c_str()));
    nodes.push_back(node(ConditionTreeNode::Kind::Condition, depth, "leaf"));
    CHECK_STR_EQ(folder_context_uid(nodes, nodes.size() - 1), std::to_string(depth));
    CHECK_STR_EQ(folder_context_uid(nodes, 0), "1");
    CHECK_STR_EQ(folder_context_uid(nodes, 4000), "4001");
}

