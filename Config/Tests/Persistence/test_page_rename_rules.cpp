// The unit is the UTF-16 code unit, not the byte and not the code point (N-M1-13; Access VARCHAR(255) holds UTF-16 units; Python len() would
// count one for an emoji, so these are stricter than Windows' own len):
//   255 x U+00E9 = 510 bytes, 255 units  -> accepted (a byte count would refuse it);
//   127 x emoji = 254 units, 128 x emoji = 256 units; 127 x emoji + 'A' = 255 -> accepted; + 'AB' = 256 -> refused;
//   253 'A' + emoji = 255 units -> accepted; 254 'A' + emoji = 256 units (255 code points!) -> refused: the astral character that crosses
//   the boundary; U+FFFF (a noncharacter, valid, one unit) counts one.
TEST(PageRenameRule, Length_CountsUtf16UnitsNotBytesAndNotCodePoints)
{
    const std::string e_acute = "\xC3\xA9";
    expect_plan(repeat(e_acute, 255), "Old", PageRenameDecision::Write, repeat(e_acute, 255));
    expect_plan(repeat(e_acute, 256), "Old", PageRenameDecision::TooLong, repeat(e_acute, 256));

    expect_plan(repeat(kEmoji, 127), "Old", PageRenameDecision::Write, repeat(kEmoji, 127));
    expect_plan(repeat(kEmoji, 128), "Old", PageRenameDecision::TooLong, repeat(kEmoji, 128));
    expect_plan(repeat(kEmoji, 127) + "A", "Old", PageRenameDecision::Write, repeat(kEmoji, 127) + "A");
    expect_plan(repeat(kEmoji, 127) + "AB", "Old", PageRenameDecision::TooLong, repeat(kEmoji, 127) + "AB");

    expect_plan(repeat("A", 253) + kEmoji, "Old", PageRenameDecision::Write, repeat("A", 253) + kEmoji);
    expect_plan(repeat("A", 254) + kEmoji, "Old", PageRenameDecision::TooLong, repeat("A", 254) + kEmoji);
    expect_plan(kEmoji + repeat("A", 254), "Old", PageRenameDecision::TooLong, kEmoji + repeat("A", 254));

    const std::string noncharacter = "\xEF\xBF\xBF"; // U+FFFF
    expect_plan(repeat(noncharacter, 255), "Old", PageRenameDecision::Write, repeat(noncharacter, 255));
    expect_plan(repeat(noncharacter, 256), "Old", PageRenameDecision::TooLong, repeat(noncharacter, 256));
}

