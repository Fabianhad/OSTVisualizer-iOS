    const char *name_of(PageRenameDecision decision)
    {
        switch (decision)
        {
        case PageRenameDecision::Refused:
            return "Refused";
        case PageRenameDecision::TooLong:
            return "TooLong";
        case PageRenameDecision::Invalid:
            return "Invalid";
        case PageRenameDecision::Unchanged:
            return "Unchanged";
        case PageRenameDecision::Write:
            return "Write";
        }
        return "<not a decision>";
    }

    // "Write:'Plan A'": the whole plan in one string, so a failure shows both the decision and the name.
    std::string show(const PageRenamePlan &plan)
    {
        return std::string(name_of(plan.decision)) + ":'" + plan.new_name + "'";
    }

