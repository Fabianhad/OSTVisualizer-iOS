// rename_page_dialog.py:141-145: `new_name = text.strip()`; `if not new_name:` show_warning("Validation Error", ...), the dialog stays open.
// Every row of the generated table whose outcome is R (empty, spaces, tab/newline, U+001C..U+001F, U+0085, U+00A0, U+1680, U+2000..U+200A,
// U+2028/2029, U+202F, U+205F, U+3000, mixes) is Refused with an empty new name, whatever the stored name is.
TEST(PageRenameRule, Oracle_TheRowsWindowsRefusesAsBlankAreRefused)
{
    int rows = 0;
    for (const DecisionRow &row : kDecisionRows)
    {
        if (row.outcome != 'R')
            continue;
        ++rows;
        SCOPED_CONTEXT(std::string("blank row: ") + row.what);
        expect_plan(from_hex(row.entered), from_hex(row.stored), PageRenameDecision::Refused, "");
    }
    CHECK_EQ(rows, 50); // the generated table has 50 blank rows
}

// rename_page_dialog.py:146-148: the stripped text against the STORED (unstripped) name; anything else is saved stripped. The W and U rows
// of the table without a NUL: Write with the stripped text, or Unchanged (the stripped text is the stored name). Includes the case-only
// change (a101 -> A101 is W), a stored name with surrounding spaces (entered 'A', stored ' A ' is W) and the characters that str.isspace()
// does NOT strip (U+180E, U+200B, U+FEFF: kept).
TEST(PageRenameRule, Oracle_TheRowsWindowsWritesOrLeavesUnchangedAreTheSameDecisions)
{
    int writes = 0;
    int unchanged = 0;
    for (const DecisionRow &row : kDecisionRows)
    {
        if (row.outcome == 'R')
            continue;
        const std::string new_name = from_hex(row.new_name);
        if (has_nul(new_name))
            continue; // the documented deviation, next test
        SCOPED_CONTEXT(std::string("row: ") + row.what + " stored " + from_hex(row.stored));
        if (row.outcome == 'W')
        {
            ++writes;
            expect_plan(from_hex(row.entered), from_hex(row.stored), PageRenameDecision::Write, new_name);
        }
        else
        {
            ++unchanged;
            expect_plan(from_hex(row.entered), from_hex(row.stored), PageRenameDecision::Unchanged, new_name);
        }
    }
    CHECK_EQ(writes, 83);   // the generated table has 83 W rows without a NUL (91 with the 8 NUL rows)
    CHECK_EQ(unchanged, 14);
}

