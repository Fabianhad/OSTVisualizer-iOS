    std::string from_hex(const char *hex)
    {
        std::string out;
        for (const char *p = hex; p[0] != '\0' && p[1] != '\0'; p += 2)
        {
            const char pair[3] = {p[0], p[1], '\0'};
            out.push_back(static_cast<char>(std::stoi(pair, nullptr, 16)));
        }
        return out;
    }

    std::string repeat(const std::string &unit, std::size_t count)
    {
        std::string out;
        out.reserve(unit.size() * count);
        for (std::size_t i = 0; i < count; ++i)
            out += unit;
        return out;
    }

