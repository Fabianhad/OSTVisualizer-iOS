// Port of tests/domain/services/test_uom_service.py::UomValidUnitTests::test_system_normalization_maps_each_unit_to_its_counterpart
TEST(Qty06_UomNormalization, SystemNormalizationMapsEachUnitToItsCounterpart)
{
    const int imperial_to_metric[][2] = {{1, 13}, {2, 13}, {3, 13}, {4, 14}, {5, 14}, {6, 14}, {7, 14}, {8, 16}, {9, 16}};
    for (const auto &p : imperial_to_metric)
    {
        SCOPED_CONTEXT("code " + std::to_string(p[0]));
        CHECK_EQ(normalize_uom_for_system(p[0], true), p[1]);
        CHECK_EQ(normalize_uom_for_system(p[0], false), p[0]);
    }
    const int metric_to_imperial[][2] = {{11, 2}, {13, 2}, {12, 5}, {14, 5}, {15, 8}, {16, 8}};
    for (const auto &p : metric_to_imperial)
    {
        SCOPED_CONTEXT("code " + std::to_string(p[0]));
        CHECK_EQ(normalize_uom_for_system(p[0], false), p[1]);
        CHECK_EQ(normalize_uom_for_system(p[0], true), p[0]);
    }
    for (int code : {0, 10, 99})
    {
        SCOPED_CONTEXT("code " + std::to_string(code));
        CHECK_EQ(normalize_uom_for_system(code, true), code);
        CHECK_EQ(normalize_uom_for_system(code, false), code);
    }
}

