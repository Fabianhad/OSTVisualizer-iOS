// Windows probe (UNITS-M01 / DBP-06): a loaded BidConditions row is normalized with
// metric = (MeasureBase == 1): MeasureBase 1: (Quantity1=1, UOM1=2) -> 13; (20, 8) -> 16; (11, 5) -> 14;
// (23, 0) -> 0.  MeasureBase 0: (1, 13) -> 2; (11, 14) -> 5; (20, 16) -> 8; (23, 2) -> 0;
// and (11, 2) -> 5 in an imperial bid.  The loader wiring itself lives in ProjectStore+Load.cpp.
TEST(Qty06_UomNormalization, LoaderRowsNormalizeLikeTheWindowsProbe)
{
    struct Probe
    {
        bool metric;
        int calc, uom, expected;
    };
    const Probe probes[] = {
        {true, 1, 2, 13},
        {true, 20, 8, 16},
        {true, 11, 5, 14},
        {true, 23, 0, 0},
        {false, 1, 13, 2},
        {false, 11, 14, 5},
        {false, 20, 16, 8},
        {false, 23, 2, 0},
        {false, 11, 2, 5},
    };
    for (const Probe &p : probes)
    {
        SCOPED_CONTEXT(std::string(p.metric ? "metric" : "imperial") + " calc " + std::to_string(p.calc) +
                       " uom " + std::to_string(p.uom));
        Condition c = make_condition("c", ConditionType::Linear, p.calc, p.uom);
        normalize_condition_uoms_for_system(c, p.metric);
        CHECK_EQ(c.uom1, p.expected);
    }
}
