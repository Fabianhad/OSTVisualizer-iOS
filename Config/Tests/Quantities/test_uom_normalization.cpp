// Port of tests/domain/services/test_uom_service.py::UomValidUnitTests::test_calculation_normalization_keeps_valid_units_and_falls_back_to_the_first_valid
// and the QTY-06 test plan values.
TEST(Qty06_UomNormalization, CalculationNormalizationKeepsValidUnitsAndFallsBackToTheFirstValid)
{
    auto norm = [](int calc, int uom, bool metric)
    { return normalize_uom_for_calculation(calc, uom, metric); };
    // calc type 0 only converts between systems.
    CHECK_EQ(norm(0, 2, true), 13);
    CHECK_EQ(norm(0, 13, false), 2);
    // An area calculation keeps a valid area unit, converts a metric one and replaces a length unit
    // with the first area unit.
    CHECK_EQ(norm(11, UOM_SQUARE_YARDS, false), 6);
    CHECK_EQ(norm(11, UOM_SQUARE_YARDS, true), 14);
    CHECK_EQ(norm(11, UOM_LINEAR_FEET, false), 5);
    CHECK_EQ(norm(11, UOM_M, true), 14);
    CHECK_EQ(norm(11, UOM_MM2, true), 12);
    // Length and volume families.
    CHECK_EQ(norm(1, UOM_INCHES, false), 1);
    CHECK_EQ(norm(1, UOM_SQUARE_FEET, false), 2);
    CHECK_EQ(norm(1, UOM_INCHES, true), 13);
    CHECK_EQ(norm(CALC_VOLUME, UOM_CUBIC_YARDS, false), 9);
    CHECK_EQ(norm(CALC_VOLUME, UOM_EACH, false), 8);
    CHECK_EQ(norm(CALC_VOLUME, UOM_EACH, true), 16);
    // Counts always use EACH.
    CHECK_EQ(norm(CALC_COUNT, UOM_LINEAR_FEET, false), 0);
    CHECK_EQ(norm(CALC_COUNT, UOM_M, true), 0);
    // QTY-06 plan: the remaining listed pairs.
    CHECK_EQ(norm(11, 2, false), 5);
    CHECK_EQ(norm(11, 13, true), 14);
    CHECK_EQ(norm(11, 12, true), 12);
    CHECK_EQ(norm(11, 6, false), 6);
    CHECK_EQ(norm(11, 6, true), 14);
    CHECK_EQ(norm(1, 1, false), 1);
    CHECK_EQ(norm(1, 5, false), 2);
    CHECK_EQ(norm(1, 1, true), 13);
    CHECK_EQ(norm(20, 9, false), 9);
    CHECK_EQ(norm(20, 0, false), 8);
    CHECK_EQ(norm(20, 0, true), 16);
    CHECK_EQ(norm(23, 2, false), 0);
    CHECK_EQ(norm(23, 13, true), 0);
}

