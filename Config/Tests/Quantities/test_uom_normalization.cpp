// Port of tests/domain/services/test_uom_service.py::UomValidUnitTests::test_calculation_normalization_over_tuples_and_conditions
// and the COND-UOMNORM-01 / UNITS-M01 plans.
TEST(Qty06_UomNormalization, CalculationNormalizationOverTuplesAndConditions)
{
    CHECK(normalize_uoms_for_calculations(V{11, 1, 23}, V{2, 5, 2}, false) == V({5, 2, 0}));
    CHECK(normalize_uoms_for_calculations(V{}, V{}, true) == V());
    // imperial invalid-pair repair (every bid, not only metric ones)
    CHECK(normalize_uoms_for_calculations(V{1, 0, 0}, V{5, -1, -1}, false) == V({2, -1, -1}));
    CHECK(normalize_uoms_for_calculations(V{23, 0, 0}, V{2, -1, -1}, false) == V({0, -1, -1}));
    CHECK(normalize_uoms_for_calculations(V{24, 0, 0}, V{0, 0, 0}, false) == V({2, 0, 0}));
    CHECK(normalize_uoms_for_calculations(V{11, 15, 21}, V{2, 2, 2}, false) == V({5, 2, 8}));
    CHECK(normalize_uoms_for_calculations(V{20, 0, 0}, V{5, 0, 0}, false) == V({8, 0, 0}));
    CHECK(normalize_uoms_for_calculations(V{4, 0, 0}, V{7, 0, 0}, false) == V({7, 0, 0}));
    CHECK(normalize_uoms_for_calculations(V{0, 0, 0}, V{-1, -1, -1}, false) == V({-1, -1, -1}));

    Condition condition;
    condition.uid = "c";
    condition.calc_type1 = 11;
    condition.calc_type2 = 1;
    condition.calc_type3 = 0;
    condition.uom1 = UOM_LINEAR_FEET;
    condition.uom2 = UOM_SQUARE_FEET;
    condition.uom3 = UOM_LINEAR_FEET;
    Condition &returned = normalize_condition_uoms_for_system(condition, true);
    CHECK(&returned == &condition);
    CHECK_EQ(condition.uom1, 14);
    CHECK_EQ(condition.uom2, 13);
    CHECK_EQ(condition.uom3, 13);
    normalize_condition_uoms_for_system(condition, false);
    CHECK_EQ(condition.uom1, 5);
    CHECK_EQ(condition.uom2, 2);
    CHECK_EQ(condition.uom3, 2);
}

